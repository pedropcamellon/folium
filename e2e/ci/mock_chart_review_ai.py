from __future__ import annotations

import json
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from typing import Any


class MockChatCompletionHandler(BaseHTTPRequestHandler):
    def do_GET(self) -> None:
        if self.path != "/health":
            self.send_error(404)
            return
        self.send_response(200)
        self.send_header("Content-Length", "0")
        self.end_headers()

    def do_POST(self) -> None:
        if self.path != "/v1/chat/completions":
            self.send_error(404)
            return

        try:
            request = json.loads(self.rfile.read(int(self.headers["Content-Length"])))
            payload = self._completion_payload(request)
        except (KeyError, TypeError, ValueError, json.JSONDecodeError) as error:
            self.send_error(400, str(error))
            return

        body = json.dumps(
            {
                "id": "chatcmpl-e2e-mock",
                "object": "chat.completion",
                "created": 0,
                "model": "e2e-mock",
                "choices": [
                    {
                        "index": 0,
                        "message": {
                            "role": "assistant",
                            "content": json.dumps(payload),
                        },
                        "finish_reason": "stop",
                    }
                ],
            }
        ).encode()
        self.send_response(200)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    @staticmethod
    def _completion_payload(request: Any) -> dict[str, Any]:
        messages = request.get("messages")
        if not isinstance(messages, list):
            raise ValueError("Expected a messages array")
        prompt = "\n".join(
            str(message.get("content", ""))
            for message in messages
            if isinstance(message, dict)
        )
        marker = "Allowed source IDs: "
        if marker not in prompt:
            return {"search_terms": []}

        allowed_source_ids_json = prompt.split(marker, maxsplit=1)[1].split(
            "\n", maxsplit=1
        )[0]
        allowed_source_ids = json.loads(allowed_source_ids_json)
        if not isinstance(allowed_source_ids, list) or not all(
            isinstance(source_id, str) for source_id in allowed_source_ids
        ):
            raise ValueError("Expected a list of allowed source IDs")

        source_refs = (
            [{"source_id": allowed_source_ids[0]}] if allowed_source_ids else []
        )
        return {
            "summary": "Synthetic chart review draft generated by the CI mock.",
            "reasoning": "The CI mock returns a fixed response for workflow validation.",
            "confidence": "medium",
            "source_refs": source_refs,
            "missing_info": [],
            "follow_up_questions": [],
            "review_flags": [],
        }

    def log_message(self, format: str, *args: Any) -> None:
        if self.path != "/health":
            super().log_message(format, *args)


if __name__ == "__main__":
    ThreadingHTTPServer(("0.0.0.0", 8002), MockChatCompletionHandler).serve_forever()
